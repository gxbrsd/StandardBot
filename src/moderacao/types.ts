export interface ModerationChannelReference {

    /*
    |--------------------------------------------------------------------------
    | ID ATUAL
    |--------------------------------------------------------------------------
    |
    | Pode mudar depois de /modelo restaurar.
    |
    */

    id:
        string | null;


    /*
    |--------------------------------------------------------------------------
    | NOME DE FALLBACK
    |--------------------------------------------------------------------------
    |
    | Mesma filosofia do ticket:
    |
    | ID morreu
    | ↓
    | procura pelo nome
    | ↓
    | repara se houver exatamente um
    |
    */

    name:
        string;
}


/*
|--------------------------------------------------------------------------
| CONFIGURAÇÃO
|--------------------------------------------------------------------------
*/

export interface ModerationConfig {

    /*
    |--------------------------------------------------------------------------
    | CANAL DE LOGS
    |--------------------------------------------------------------------------
    |
    | Exemplo:
    |
    | #logs-mod
    |
    */

    logsChannel:
        ModerationChannelReference | null;


    updatedAt:
        string;
}


/*
|--------------------------------------------------------------------------
| WARNING
|--------------------------------------------------------------------------
*/

export interface WarningRecord {

    /*
    |--------------------------------------------------------------------------
    | ID DO WARNING
    |--------------------------------------------------------------------------
    |
    | Exemplo:
    |
    | #1
    | #2
    | #3
    |
    */

    id:
        number;


    /*
    |--------------------------------------------------------------------------
    | SERVIDOR
    |--------------------------------------------------------------------------
    */

    guildId:
        string;


    /*
    |--------------------------------------------------------------------------
    | USUÁRIO ADVERTIDO
    |--------------------------------------------------------------------------
    */

    userId:
        string;


    /*
    |--------------------------------------------------------------------------
    | MODERADOR
    |--------------------------------------------------------------------------
    */

    moderatorId:
        string;


    /*
    |--------------------------------------------------------------------------
    | MOTIVO
    |--------------------------------------------------------------------------
    */

    reason:
        string;


    /*
    |--------------------------------------------------------------------------
    | DATA
    |--------------------------------------------------------------------------
    */

    createdAt:
        string;
}


/*
|--------------------------------------------------------------------------
| ESTADO ANTERIOR DO SEND MESSAGES
|--------------------------------------------------------------------------
|
| Necessário para:
|
| /lock
| /unlock
|
|
| Exemplo:
|
| antes:
|
| @everyone
| SendMessages = herdado
|
| /lock
| ↓
| SendMessages = false
|
| /unlock
| ↓
| volta para herdado
|
|
| Assim /unlock não sai simplesmente dando:
|
| SendMessages = true
|
| e quebrando permissões que já existiam.
|
|--------------------------------------------------------------------------
*/

export type PreviousSendMessagesState =
    | 'allow'
    | 'deny'
    | 'inherit';


/*
|--------------------------------------------------------------------------
| REGISTRO DE LOCK
|--------------------------------------------------------------------------
*/

export interface ChannelLockRecord {

    channelId:
        string;


    channelName:
        string;


    previousSendMessages:
        PreviousSendMessagesState;


    lockedById:
        string;


    lockedAt:
        string;
}


/*
|--------------------------------------------------------------------------
| DADOS DO SERVIDOR
|--------------------------------------------------------------------------
*/

export interface ModerationGuildData {

    schemaVersion:
        1;


    guildId:
        string;


    config:
        ModerationConfig;


    /*
    |--------------------------------------------------------------------------
    | WARNINGS
    |--------------------------------------------------------------------------
    */

    warnings:
        WarningRecord[];


    /*
    |--------------------------------------------------------------------------
    | PRÓXIMO ID
    |--------------------------------------------------------------------------
    */

    nextWarningId:
        number;


    /*
    |--------------------------------------------------------------------------
    | CANAIS TRANCADOS PELO BOT
    |--------------------------------------------------------------------------
    |
    | Guardamos isso porque /unlock precisa saber
    | qual era a situação ANTES do /lock.
    |
    */

    lockedChannels:
        ChannelLockRecord[];
}